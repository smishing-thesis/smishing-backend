from typing import Protocol
from uuid import UUID


class ManagementError(Exception):
    def __init__(self, status: int):
        self.status = status


class AdministrationRepository(Protocol):
    def list(self, resource: str, limit: int, offset: int) -> list[dict]: ...
    def get(self, resource: str, identity: UUID) -> dict: ...
    def create(self, resource: str, values: dict) -> dict: ...
    def change(self, resource: str, identity: UUID, values: dict) -> dict: ...
    def delete(self, resource: str, identity: UUID) -> None: ...
